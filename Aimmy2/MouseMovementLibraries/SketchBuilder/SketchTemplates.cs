using System.Text;

namespace Whales2.MouseMovementLibraries.SketchBuilder
{
    /// <summary>
    /// The Arduino Leonardo + USB Host Shield sketches the sketch builder writes:
    /// the report logger, and the mouse pass-through sketch controlled over the COM port or Raw HID.
    /// Both pass-through sketches need the "USB Host Shield Library 2.0" and NicoHood's "HID-Project".
    /// </summary>
    internal static class SketchTemplates
    {
        /// <summary>Raw HID firmware version answered to PING (Whales shows it when connecting).</summary>
        public const int FirmwareMajor = 1, FirmwareMinor = 0;

        /// <summary>Prints every HID report from the mouse on the Host Shield as hex, one report per line.</summary>
        public const string ReportLogger =
@"// Whales report logger: prints each HID report from the mouse on the USB Host Shield, as hex.
// Needs: USB Host Shield Library 2.0. Board: Arduino Leonardo.
#include <SPI.h>
#include <Usb.h>
#include <hiduniversal.h>
#include <usbhub.h>

USB Usb;
USBHub Hub(&Usb);
HIDUniversal Hid(&Usb);

class RawHIDParser : public HIDReportParser {
  public:
  void Parse(USBHID* hid, bool is_rpt_id, uint8_t len, uint8_t* buf) override {
    for (uint8_t i = 0; i < len; i++) {
      if (buf[i] < 16) Serial.print(""0"");
      Serial.print(buf[i], HEX);
      Serial.print("" "");
    }
    Serial.println();
  }
};

RawHIDParser rawParser;

void setup() {
  Serial.begin(115200);
  while (!Serial); // wait for the PC to open the port
  if (Usb.Init() == -1) {
    Serial.println(""USB Host Shield init failed"");
    while (1);
  }
  Hid.SetReportParser(0, &rawParser);
  Serial.println(""USB Host Shield ready. Waiting For Mouse Movements/Clicks"");
}

void loop() {
  Usb.Task();
}
";

        /// <summary>Pass-through sketch, controlled with "x,y,click\n" lines over the COM port (the protocol Whales' Arduino option sends).</summary>
        public static string Com(MouseReportLayout layout) => Build(layout, rawHid: false);

        /// <summary>Pass-through sketch, controlled with 64-byte Raw HID reports (the protocol Whales' Arduino (Raw HID) option sends).</summary>
        public static string RawHid(MouseReportLayout layout) => Build(layout, rawHid: true);

        private static string Build(MouseReportLayout l, bool rawHid)
        {
            var s = new StringBuilder();
            s.Append(rawHid
                ? "// Whales mouse pass-through, controlled over Raw HID (pick \"Arduino (Raw HID)\" in Whales).\n"
                : "// Whales mouse pass-through, controlled over the COM port (pick \"Arduino\" in Whales).\n");
            s.Append("// Generated by Whales' sketch builder for this mouse:\n");
            s.Append("//   ").Append(l.Describe()).Append('\n');
            s.Append("// Needs: USB Host Shield Library 2.0 and HID-Project (NicoHood). Board: Arduino Leonardo.\n\n");

            s.Append(@"#include <SPI.h>
#include <Usb.h>
#include <usbhub.h>
#include <hiduniversal.h>
#include <HID-Project.h>
#include <HID-Settings.h>

USB          Usb;
USBHub       Hub(&Usb);
HIDUniversal Hid(&Usb);

// ---- Your mouse's report layout (detected by Whales) ----
");
            s.Append($"static const uint8_t REPORT_MIN_LENGTH = {l.MinLength};\n");
            s.Append($"static const int16_t REPORT_ID         = {l.ReportId};   // -1 = no report ID\n");
            s.Append($"static const uint8_t BUTTONS_OFFSET    = {l.ButtonsOffset};\n");
            s.Append($"static const uint8_t LEFT_MASK         = 0x{l.LeftMask:X2};\n");
            s.Append($"static const uint8_t RIGHT_MASK        = 0x{l.RightMask:X2};\n");
            s.Append($"static const uint8_t MIDDLE_MASK       = 0x{l.MiddleMask:X2};\n");
            s.Append($"static const uint8_t DX_OFFSET         = {l.XOffset};\n");
            s.Append($"static const uint8_t DY_OFFSET         = {l.YOffset};\n");
            s.Append($"static const int16_t WHEEL_OFFSET      = {l.WheelOffset};   // -1 = no wheel\n");
            s.Append($"#define XY_FORMAT {(l.Format switch { XyFormat.Bits8 => 8, XyFormat.Bits16 => 16, _ => 12 })}   // 8 / 16-bit fields, or 12 = two 12-bit values packed in 3 bytes\n\n");

            s.Append(@"uint8_t physicalButtons = 0;   // held on the real mouse
uint8_t pcButtons = 0;         // held by Whales
uint8_t sentButtons = 0;

// Real mouse buttons and buttons held by Whales are combined, so neither releases the other
void applyButtons() {
  uint8_t b = physicalButtons | pcButtons;
  uint8_t pressNow = b & ~sentButtons;
  uint8_t releaseNow = sentButtons & ~b;
  if (pressNow) BootMouse.press(pressNow);
  if (releaseNow) BootMouse.release(releaseNow);
  sentButtons = b;
}

// BootMouse.move() takes -128..127 per axis, so bigger moves are sent in steps
void moveBy(int dx, int dy, int wheel) {
  do {
    int stepX = constrain(dx, -127, 127);
    int stepY = constrain(dy, -127, 127);
    BootMouse.move(stepX, stepY, constrain(wheel, -127, 127));
    dx -= stepX;
    dy -= stepY;
    wheel = 0;
  } while (dx != 0 || dy != 0);
}

static inline int16_t sign12(uint16_t v) { return (v & 0x800) ? (int16_t)(v | 0xF000) : (int16_t)v; }

class MouseParser : public HIDReportParser {
  void Parse(USBHID*, bool, uint8_t len, uint8_t *buf) override {
    if (len < REPORT_MIN_LENGTH) return;
    if (REPORT_ID >= 0 && buf[0] != REPORT_ID) return;   // another kind of report (e.g. media keys)

    uint8_t raw = buf[BUTTONS_OFFSET];
    uint8_t b = 0;
    if (raw & LEFT_MASK) b |= MOUSE_LEFT;
    if (raw & RIGHT_MASK) b |= MOUSE_RIGHT;
    if (MIDDLE_MASK && (raw & MIDDLE_MASK)) b |= MOUSE_MIDDLE;

#if XY_FORMAT == 8
    int dx = (int8_t)buf[DX_OFFSET];
    int dy = (int8_t)buf[DY_OFFSET];
#elif XY_FORMAT == 16
    int dx = (int16_t)(buf[DX_OFFSET] | (buf[DX_OFFSET + 1] << 8));
    int dy = (int16_t)(buf[DY_OFFSET] | (buf[DY_OFFSET + 1] << 8));
#else
    int dx = sign12(buf[DX_OFFSET] | ((buf[DX_OFFSET + 1] & 0x0F) << 8));
    int dy = sign12((buf[DX_OFFSET + 1] >> 4) | (buf[DX_OFFSET + 2] << 4));
#endif
    int wheel = WHEEL_OFFSET >= 0 ? (int8_t)buf[WHEEL_OFFSET] : 0;

    if (dx != 0 || dy != 0 || wheel != 0) moveBy(dx, dy, wheel);
    physicalButtons = b;
    applyButtons();
  }
} mouseParser;

");
            s.Append(rawHid ? RawHidControl : ComControl);
            return s.ToString().Replace("\r\n", "\n");
        }

        // COM: "x,y,click\n". click != 0 = one left click. Same protocol as the Arduino sketches Whales already uses.
        private const string ComControl = @"// ---- Control from Whales over the COM port: ""x,y,click\n"" ----
char line[32];
uint8_t lineLength = 0;

void handleLine() {
  line[lineLength] = 0;
  char *p = line;
  long x = strtol(p, &p, 10); if (*p != ',') return; p++;
  long y = strtol(p, &p, 10); if (*p != ',') return; p++;
  long click = strtol(p, &p, 10);

  if (x != 0 || y != 0) moveBy(x, y, 0);
  if (click != 0) {
    pcButtons |= MOUSE_LEFT;  applyButtons();
    pcButtons &= ~MOUSE_LEFT; applyButtons();
  }
}

void pollSerial() {
  while (Serial.available() > 0) {
    char c = Serial.read();
    if (c == '\n' || c == '\r') {
      if (lineLength > 0) handleLine();
      lineLength = 0;
    } else if (lineLength < sizeof(line) - 1) {
      line[lineLength++] = c;
    } else {
      lineLength = 0;   // too long: not a command, drop it
    }
  }
}

void setup() {
  Serial.begin(115200);
  BootMouse.begin();
  if (Usb.Init() == -1) while (1);   // USB Host Shield didn't start
  Hid.SetReportParser(0, &mouseParser);
}

void loop() {
  Usb.Task();
  pollSerial();
}
";

        // Raw HID: 64-byte reports, byte 0 = command (the protocol in Whales' ArduinoHidDevice)
        private static readonly string RawHidControl = @"// ---- Control from Whales over Raw HID (64-byte reports, byte 0 = command) ----
//   0x01 MOVE     int16 dx, int16 dy (little endian), int8 wheel
//   0x02 BUTTONS  button mask held by Whales (bit0 left, bit1 right, bit2 middle, bit3 back, bit4 forward)
//   0x03 CLICK    button index (0-4), hold ms (0 = 15 ms)
//   0x05 RESET    release everything Whales holds
//   0x10 PING     replies 0x10, firmware major, minor (Whales checks this before connecting)
uint8_t rawRx[64];
uint8_t rawTx[64];

static inline int16_t le16(const uint8_t *p) { return (int16_t)(p[0] | (p[1] << 8)); }

void handleCommand(const uint8_t *c) {
  switch (c[0]) {
    case 0x01:
      moveBy(le16(&c[1]), le16(&c[3]), (int8_t)c[5]);
      break;
    case 0x02:
      pcButtons = c[1] & 0x1F;
      applyButtons();
      break;
    case 0x03:
      if (c[1] < 5) {
        uint8_t m = 1 << c[1];
        pcButtons |= m;  applyButtons();
        delay(c[2] ? c[2] : 15);
        pcButtons &= ~m; applyButtons();
      }
      break;
    case 0x05:
      pcButtons = 0;
      applyButtons();
      break;
    case 0x10:
      memset(rawTx, 0, sizeof(rawTx));
      rawTx[0] = 0x10;
      rawTx[1] = " + FirmwareMajor + @";
      rawTx[2] = " + FirmwareMinor + @";
      RawHID.write(rawTx, sizeof(rawTx));
      break;
  }
}

// A new report is only accepted once the previous one has been read, so check often
void pollRawHid() {
  int n = RawHID.available();
  if (n <= 0) return;
  uint8_t cmd[64] = {0};
  for (int i = 0; i < n; i++) {
    int b = RawHID.read();
    if (i < 64) cmd[i] = (uint8_t)b;
  }
  handleCommand(cmd);
}

void setup() {
  Serial.begin(115200);   // kept so the board can still be uploaded to normally
  BootMouse.begin();
  RawHID.begin(rawRx, sizeof(rawRx));
  if (Usb.Init() == -1) while (1);   // USB Host Shield didn't start
  Hid.SetReportParser(0, &mouseParser);
}

void loop() {
  pollRawHid();
  Usb.Task();
  pollRawHid();
}
";
    }
}
